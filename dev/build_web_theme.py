"""Compile modular reviewed theme sources to existing static asset routes; no runtime dependency."""
import argparse
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
THEME=ROOT/'src/ui/theme'

def builds():
    shared=['tokens.css','shell.css','components.css','integration.css']
    # Main app: premium application shell (Oct 2026), one source file. Forge keeps the Muse Wonder theme.
    for target,names in [('src/ui/style.css',['app.css','command.css']),('src/forge/ui/forge.css',['forge-legacy.css',*shared])]:
        yield ROOT/target,'/* Generated by python -m dev.build_web_theme. Edit src/ui/theme sources. */\n'+''.join('\n/* '+name+' */\n'+(THEME/name).read_text(encoding='utf-8').strip()+'\n' for name in names)

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,content in builds():
        if a.check:
            if path.read_text(encoding='utf-8')!=content:raise SystemExit('Theme build differs: '+str(path.relative_to(ROOT)))
        else:path.write_text(content,encoding='utf-8')
    print('Web theme sources match compiled assets.' if a.check else 'Compiled both web themes.')

if __name__=='__main__':main()
